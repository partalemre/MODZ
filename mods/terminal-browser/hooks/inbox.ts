import { takenItems } from './bridge-protocol'
import { post } from './bridge-client'
import type { Host } from './host'
import { state } from './session'

export async function deliverAgentText(host: Host): Promise<void> {
  const oneLine = (text: string) => text.replace(/[\x00-\x1f\x7f-\x9f]/g, ' ').replace(/\s+/g, ' ').trim()
  const lines = takenItems(await post(host, '/inbox/take', {}))
    .filter(item => item.text.trim() !== '')
    .flatMap(item => [oneLine(item.text), ...(item.screenshot ? [oneLine(item.screenshot)] : [])])
  if (lines.length === 0) return
  const { isFilled } = await host.fill({ text: `${lines.join('\n')}\n` })
  if (!isFilled) {
    // would need to see a case this happens before shipping
    // $.ui.toast('copied to clipboard')
    return
  }
  state.viewGeneration += 1
  host.redraw()
}
