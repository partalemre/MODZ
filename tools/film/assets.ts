// Writes the film's sprites from the repo's own sources, so the film draws the same crabs, pixel glyphs,
// letters and icons the mods draw: savvy-progress's crabs, kit/pixels.ts and kit/icons.ts.
// Run: bun tools/film/assets.ts   (render.mjs runs it before every render; the output is not committed)
import { crab } from '../../mods/savvy-progress/hooks/crabs'
import { PIXEL_GLYPHS } from '../../kit/pixels'
import { ICON_NAMES, icon } from '../../kit/icons'

const CLAY = '#D97757'
const CREW = {
  hero: { costume: 'other', shell: CLAY },
  heavy: { costume: 'heavy', shell: '#E07A9A' },
  careful: { costume: 'careful', shell: CLAY },
  light: { costume: 'light', shell: '#6BB26F' },
  medium: { costume: 'medium', shell: '#4FA3C7' },
  explore: { costume: 'explore', shell: '#7C93B8' },
  fable: { costume: 'fable', shell: '#B07CC6' },
} as const
const MOODS = ['happy', 'worried', 'sleeping'] as const

// One 30×28 sprite per crab, legs left free: the film moves them by the distance walked.
const sprite = (costume: string, shell: string, mood?: (typeof MOODS)[number]): string =>
  crab(0, 0, { costume, look: { shell, eyes: 'dot', name: '' }, scale: 1, mood })

const crabs: Record<string, string> = Object.fromEntries(Object.entries(CREW).map(([k, c]) => [k, sprite(c.costume, c.shell)]))
for (const mood of MOODS) crabs[`hero-${mood}`] = sprite('other', CLAY, mood)

const LETTERS = {
  M: ['X...X', 'XX.XX', 'X.X.X', 'X.X.X', 'X...X', 'X...X', 'X...X'],
  O: ['.XXX.', 'X...X', 'X...X', 'X...X', 'X...X', 'X...X', '.XXX.'],
  D: ['XXXX.', 'X...X', 'X...X', 'X...X', 'X...X', 'X...X', 'XXXX.'],
  Z: ['XXXXX', '....X', '...X.', '..X..', '.X...', 'X....', 'XXXXX'],
}
const icons = Object.fromEntries(ICON_NAMES.map(n => [n, icon(n)]))

const out = `// Generated by tools/film/assets.ts. Do not edit.
export const CRABS = ${JSON.stringify(crabs)}
export const GLYPHS = ${JSON.stringify(PIXEL_GLYPHS)}
export const LETTERS = ${JSON.stringify(LETTERS)}
export const ICONS = ${JSON.stringify(icons)}
`
await Bun.write(`${import.meta.dir}/src/assets.gen.js`, out)
console.log(`assets: ${Object.keys(crabs).length} crabs, ${Object.keys(PIXEL_GLYPHS).length} glyphs, ${ICON_NAMES.length} icons`)
